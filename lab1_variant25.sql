CREATE SCHEMA IF NOT EXISTS korablev25;
SET LOCAL search_path TO korablev25;

-- Для повторного запуска лабораторной удаляем только таблицы своего варианта.
DROP TABLE IF EXISTS correspondence CASCADE;
DROP TABLE IF EXISTS correspondence_types CASCADE;

-- Виды корреспонденции (главная таблица).
CREATE TABLE correspondence_types (
    type_id       INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 11) PRIMARY KEY,
    type_name     VARCHAR(80) NOT NULL,
    packaging     VARCHAR(40) NOT NULL,
    min_weight    NUMERIC(10, 2) NOT NULL CHECK (min_weight > 0),
    max_weight    NUMERIC(10, 2) NOT NULL CHECK (max_weight >= min_weight),
    min_length    NUMERIC(8, 2) NOT NULL CHECK (min_length > 0),
    min_width     NUMERIC(8, 2) NOT NULL CHECK (min_width > 0),
    min_height    NUMERIC(8, 2) NOT NULL CHECK (min_height > 0),
    max_length    NUMERIC(8, 2) NOT NULL CHECK (max_length >= min_length),
    max_width     NUMERIC(8, 2) NOT NULL CHECK (max_width >= min_width),
    max_height    NUMERIC(8, 2) NOT NULL CHECK (max_height >= min_height)
);

-- Корреспонденция (зависимая таблица).
CREATE TABLE correspondence (
    track_number   VARCHAR(40) PRIMARY KEY,
    type_id        INTEGER,
    weight_grams   NUMERIC(10, 2) NOT NULL CHECK (weight_grams > 0),
    length_cm      NUMERIC(8, 2) NOT NULL CHECK (length_cm > 0),
    width_cm       NUMERIC(8, 2) NOT NULL CHECK (width_cm > 0),
    height_cm      NUMERIC(8, 2) NOT NULL CHECK (height_cm > 0),
    sender_code    INTEGER,
    stamps_amount  NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (stamps_amount >= 0),

    -- 5. Обеспечить ссылочную целостность данных.
    CONSTRAINT fk_correspondence_type
        FOREIGN KEY (type_id) REFERENCES correspondence_types (type_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

